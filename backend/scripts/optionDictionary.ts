export function translateOptions(options: string[]): { hi: string[]; te: string[] } {
  const hi: string[] = [];
  const te: string[] = [];

  for (const opt of options) {
    const cleanOpt = opt.trim();
    if (OPTION_TRANSLATIONS[cleanOpt]) {
      hi.push(OPTION_TRANSLATIONS[cleanOpt].hi);
      te.push(OPTION_TRANSLATIONS[cleanOpt].te);
    } else {
      // Fallback: Check case-insensitive match
      const matchedKey = Object.keys(OPTION_TRANSLATIONS).find(k => k.toLowerCase() === cleanOpt.toLowerCase());
      if (matchedKey) {
        hi.push(OPTION_TRANSLATIONS[matchedKey].hi);
        te.push(OPTION_TRANSLATIONS[matchedKey].te);
      } else {
        hi.push(cleanOpt);
        te.push(cleanOpt);
      }
    }
  }

  return { hi, te };
}
